/**
 * Generates `src/lib/dashboard/australia-states-map.ts` (SVG paths per state)
 * from Natural Earth admin-1 boundaries (public domain, naturalearthdata.com).
 *
 * Usage: npx tsx scripts/maps/generate-australia-states.ts [--input <geojson>]
 * Without --input the 1:50m GeoJSON is downloaded from the natural-earth-vector repo.
 */
import { readFile, writeFile } from "node:fs/promises"
import path from "node:path"

const SOURCE_URL =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_1_states_provinces.geojson"
const OUTPUT = path.join(process.cwd(), "src", "lib", "dashboard", "australia-states-map.ts")
const VIEW_WIDTH = 1000
const PADDING = 10
const MIN_ISLAND_AREA = 12

type Ring = number[][]
type Feature = {
  properties: { adm0_a3: string; iso_3166_2: string }
  geometry: { type: "Polygon"; coordinates: Ring[] } | { type: "MultiPolygon"; coordinates: Ring[][] }
}

const STATE_BY_ISO: Record<string, string> = {
  "AU-NSW": "NSW",
  "AU-X02~": "NSW",
  "AU-VIC": "VIC",
  "AU-QLD": "QLD",
  "AU-SA": "SA",
  "AU-WA": "WA",
  "AU-TAS": "TAS",
  "AU-NT": "NT",
  "AU-ACT": "ACT",
}

const LABEL_ANCHOR_LON_LAT: Record<string, [number, number]> = {
  WA: [121.5, -25.5],
  NT: [133.4, -19.5],
  SA: [135.2, -30.2],
  QLD: [144.5, -22.5],
  NSW: [146.6, -32.4],
  VIC: [144.2, -36.9],
  TAS: [146.6, -42.0],
  ACT: [149.0, -35.45],
}

const toRadians = (degrees: number) => (degrees * Math.PI) / 180

// Lambert conformal conic, standard parallels 18°S / 36°S, central meridian 134°E.
const createProjection = () => {
  const phi1 = toRadians(-18)
  const phi2 = toRadians(-36)
  const phi0 = toRadians(-27)
  const lambda0 = toRadians(134)
  const t = (phi: number) => Math.tan(Math.PI / 4 + phi / 2)
  const n = Math.log(Math.cos(phi1) / Math.cos(phi2)) / Math.log(t(phi2) / t(phi1))
  const f = (Math.cos(phi1) * Math.pow(t(phi1), n)) / n
  const rho = (phi: number) => f / Math.pow(t(phi), n)
  const rho0 = rho(phi0)
  return ([lon, lat]: number[]): [number, number] => {
    const r = rho(toRadians(lat))
    const theta = n * (toRadians(lon) - lambda0)
    return [r * Math.sin(theta), -(rho0 - r * Math.cos(theta))]
  }
}

const ringArea = (ring: number[][]) => {
  let area = 0
  for (let index = 0; index < ring.length; index += 1) {
    const [x1, y1] = ring[index]
    const [x2, y2] = ring[(index + 1) % ring.length]
    area += x1 * y2 - x2 * y1
  }
  return Math.abs(area / 2)
}

const loadGeoJson = async (input: string | undefined) => {
  if (input) return JSON.parse(await readFile(input, "utf8")) as { features: Feature[] }
  const response = await fetch(SOURCE_URL)
  if (!response.ok) throw new Error(`Download failed: ${response.status}`)
  return (await response.json()) as { features: Feature[] }
}

const main = async () => {
  const inputIndex = process.argv.indexOf("--input")
  const geo = await loadGeoJson(inputIndex >= 0 ? process.argv[inputIndex + 1] : undefined)
  const project = createProjection()

  const polygonsByState = new Map<string, Ring[][]>()
  for (const feature of geo.features) {
    if (feature.properties.adm0_a3 !== "AUS") continue
    const state = STATE_BY_ISO[feature.properties.iso_3166_2]
    if (!state) continue
    const polygons =
      feature.geometry.type === "Polygon" ? [feature.geometry.coordinates] : feature.geometry.coordinates
    const projected = polygons.map((polygon) => polygon.map((ring) => ring.map(project)))
    polygonsByState.set(state, [...(polygonsByState.get(state) ?? []), ...projected])
  }

  const allPoints = [...polygonsByState.values()].flat(3)
  const minX = Math.min(...allPoints.map((point) => point[0]))
  const maxX = Math.max(...allPoints.map((point) => point[0]))
  const minY = Math.min(...allPoints.map((point) => point[1]))
  const maxY = Math.max(...allPoints.map((point) => point[1]))
  const scale = (VIEW_WIDTH - PADDING * 2) / (maxX - minX)
  const viewHeight = Math.ceil((maxY - minY) * scale + PADDING * 2)
  const toView = ([x, y]: number[]) => [
    Math.round(((x - minX) * scale + PADDING) * 10) / 10,
    Math.round(((y - minY) * scale + PADDING) * 10) / 10,
  ]

  const entries = [...polygonsByState.entries()].sort(([a], [b]) => a.localeCompare(b))
  const lines = entries.map(([state, polygons]) => {
    const segments: string[] = []
    for (const polygon of polygons) {
      const rings = polygon.map((ring) => ring.map(toView))
      if (ringArea(rings[0]) < MIN_ISLAND_AREA && state !== "ACT") continue
      for (const ring of rings) {
        segments.push(`M${ring.map(([x, y]) => `${x} ${y}`).join("L")}Z`)
      }
    }
    const [anchorX, anchorY] = toView(project(LABEL_ANCHOR_LON_LAT[state])).map(Math.round)
    return `  ${state}: { d: "${segments.join("")}", anchor: [${anchorX}, ${anchorY}] },`
  })

  const output = [
    "// Generated by scripts/maps/generate-australia-states.ts from Natural Earth (public domain). Do not edit.",
    "",
    "export type AustraliaStatePath = { d: string; anchor: [number, number] }",
    "",
    `export const AUSTRALIA_MAP_VIEWBOX = { width: ${VIEW_WIDTH}, height: ${viewHeight} } as const`,
    "",
    "export const AUSTRALIA_STATE_PATHS: Record<string, AustraliaStatePath> = {",
    ...lines,
    "}",
    "",
  ].join("\n")

  await writeFile(OUTPUT, output, "utf8")
  console.log(`Wrote ${OUTPUT} (${entries.length} states, viewBox ${VIEW_WIDTH}x${viewHeight})`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
